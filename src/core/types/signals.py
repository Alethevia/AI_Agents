"""Signal type definitions for trading system.

This module defines signal-related types including signal types, strengths,
and trading signal generation.
"""

from datetime import datetime
from decimal import Decimal
from enum import Enum
from typing import Any, Dict, List, Optional

from pydantic import BaseModel, Field, field_validator, model_validator


class SignalType(str, Enum):
    """Signal type enumeration."""

    BUY = "BUY"
    SELL = "SELL"
    HOLD = "HOLD"
    REDUCE = "REDUCE"
    INCREASE = "INCREASE"


class SignalStrength(str, Enum):
    """Signal strength enumeration."""

    WEAK = "WEAK"
    MODERATE = "MODERATE"
    STRONG = "STRONG"
    VERY_STRONG = "VERY_STRONG"


class Signal(BaseModel):
    """Trading signal with type, strength, and metadata.

    Represents a trading signal generated by a strategy or model with
    confidence, features, and source attribution.
    """

    # Identification
    signal_id: str = Field(..., description="Unique signal identifier")
    symbol: str = Field(..., description="Trading symbol/ticker")

    # Signal properties
    signal_type: SignalType = Field(..., description="Signal type (BUY/SELL/HOLD/etc)")
    strength: SignalStrength = Field(..., description="Signal strength")
    confidence: Decimal = Field(
        ...,
        ge=0,
        le=1,
        description="Confidence level (0-1)"
    )

    # Source and strategy
    source: str = Field(..., description="Signal source/strategy name")
    strategy_id: Optional[str] = Field(None, description="Strategy identifier")

    # Features and metadata
    features: Dict[str, Any] = Field(
        default_factory=dict,
        description="Feature values used to generate signal"
    )
    indicators: Dict[str, Decimal] = Field(
        default_factory=dict,
        description="Indicator values at signal generation"
    )

    # Recommendations
    target_price: Optional[Decimal] = Field(None, gt=0, description="Target price")
    stop_loss: Optional[Decimal] = Field(None, gt=0, description="Stop loss price")
    take_profit: Optional[Decimal] = Field(None, gt=0, description="Take profit price")
    position_size: Optional[Decimal] = Field(None, gt=0, description="Recommended position size")

    # Timing
    timestamp: datetime = Field(
        default_factory=datetime.utcnow,
        description="Signal generation timestamp"
    )
    expiry: Optional[datetime] = Field(None, description="Signal expiry time")

    # Market context
    market_price: Optional[Decimal] = Field(None, gt=0, description="Market price at generation")
    market_regime: Optional[str] = Field(None, description="Market regime classification")

    # Additional info
    notes: Optional[str] = Field(None, description="Additional notes")
    metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description="Additional metadata"
    )

    @field_validator('symbol')
    @classmethod
    def validate_symbol(cls, v: str) -> str:
        """Validate and normalize symbol."""
        if not v or not v.strip():
            raise ValueError("Symbol cannot be empty")
        return v.strip().upper()

    @field_validator('signal_id')
    @classmethod
    def validate_signal_id(cls, v: str) -> str:
        """Validate signal ID."""
        if not v or not v.strip():
            raise ValueError("Signal ID cannot be empty")
        return v.strip()

    @field_validator('source')
    @classmethod
    def validate_source(cls, v: str) -> str:
        """Validate source."""
        if not v or not v.strip():
            raise ValueError("Source cannot be empty")
        return v.strip()

    @model_validator(mode='after')
    def validate_signal(self) -> 'Signal':
        """Validate signal constraints."""
        # Validate price relationships for BUY signals
        if self.signal_type == SignalType.BUY:
            if self.market_price and self.stop_loss:
                if self.stop_loss >= self.market_price:
                    raise ValueError(
                        f"For BUY signal, stop_loss ({self.stop_loss}) must be "
                        f"below market_price ({self.market_price})"
                    )
            if self.market_price and self.take_profit:
                if self.take_profit <= self.market_price:
                    raise ValueError(
                        f"For BUY signal, take_profit ({self.take_profit}) must be "
                        f"above market_price ({self.market_price})"
                    )

        # Validate price relationships for SELL signals
        if self.signal_type == SignalType.SELL:
            if self.market_price and self.stop_loss:
                if self.stop_loss <= self.market_price:
                    raise ValueError(
                        f"For SELL signal, stop_loss ({self.stop_loss}) must be "
                        f"above market_price ({self.market_price})"
                    )
            if self.market_price and self.take_profit:
                if self.take_profit >= self.market_price:
                    raise ValueError(
                        f"For SELL signal, take_profit ({self.take_profit}) must be "
                        f"below market_price ({self.market_price})"
                    )

        # Validate expiry is in the future
        if self.expiry and self.expiry < self.timestamp:
            raise ValueError("Signal expiry cannot be before timestamp")

        return self

    def is_buy(self) -> bool:
        """Check if signal is buy type."""
        return self.signal_type in [SignalType.BUY, SignalType.INCREASE]

    def is_sell(self) -> bool:
        """Check if signal is sell type."""
        return self.signal_type in [SignalType.SELL, SignalType.REDUCE]

    def is_hold(self) -> bool:
        """Check if signal is hold type."""
        return self.signal_type == SignalType.HOLD

    def is_expired(self) -> bool:
        """Check if signal has expired."""
        if self.expiry is None:
            return False
        return datetime.utcnow() > self.expiry

    def is_strong(self) -> bool:
        """Check if signal is strong or very strong."""
        return self.strength in [SignalStrength.STRONG, SignalStrength.VERY_STRONG]

    def risk_reward_ratio(self) -> Optional[Decimal]:
        """Calculate risk/reward ratio.

        For BUY: reward = (take_profit - market_price) / (market_price - stop_loss)
        For SELL: reward = (market_price - take_profit) / (stop_loss - market_price)
        """
        if not all([self.market_price, self.stop_loss, self.take_profit]):
            return None

        if self.is_buy():
            risk = self.market_price - self.stop_loss
            reward = self.take_profit - self.market_price
        elif self.is_sell():
            risk = self.stop_loss - self.market_price
            reward = self.market_price - self.take_profit
        else:
            return None

        if risk > 0:
            return reward / risk
        return None

    def expected_return(self) -> Optional[Decimal]:
        """Calculate expected return based on confidence.

        Expected return = confidence * potential_return
        """
        if not all([self.market_price, self.take_profit]):
            return None

        if self.is_buy():
            potential_return = (self.take_profit - self.market_price) / self.market_price
        elif self.is_sell():
            potential_return = (self.market_price - self.take_profit) / self.market_price
        else:
            return None

        return self.confidence * potential_return * Decimal('100')  # Return as percentage

    def get_indicator(self, name: str) -> Optional[Decimal]:
        """Get indicator value by name."""
        return self.indicators.get(name)

    def get_feature(self, name: str) -> Any:
        """Get feature value by name."""
        return self.features.get(name)

    def time_to_expiry(self) -> Optional[int]:
        """Calculate time to expiry in seconds."""
        if self.expiry:
            delta = self.expiry - datetime.utcnow()
            return max(0, int(delta.total_seconds()))
        return None

    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary representation."""
        return {
            'signal_id': self.signal_id,
            'symbol': self.symbol,
            'signal_type': self.signal_type.value,
            'strength': self.strength.value,
            'confidence': str(self.confidence),
            'source': self.source,
            'strategy_id': self.strategy_id,
            'features': self.features,
            'indicators': {k: str(v) for k, v in self.indicators.items()},
            'target_price': str(self.target_price) if self.target_price else None,
            'stop_loss': str(self.stop_loss) if self.stop_loss else None,
            'take_profit': str(self.take_profit) if self.take_profit else None,
            'position_size': str(self.position_size) if self.position_size else None,
            'timestamp': self.timestamp.isoformat(),
            'expiry': self.expiry.isoformat() if self.expiry else None,
            'market_price': str(self.market_price) if self.market_price else None,
            'market_regime': self.market_regime,
            'notes': self.notes,
            'metadata': self.metadata,
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> 'Signal':
        """Create Signal from dictionary."""
        data_copy = data.copy()

        # Convert datetime fields
        for field in ['timestamp', 'expiry']:
            if field in data_copy and data_copy[field] is not None:
                if isinstance(data_copy[field], str):
                    data_copy[field] = datetime.fromisoformat(data_copy[field])

        # Convert decimal fields
        decimal_fields = [
            'confidence', 'target_price', 'stop_loss',
            'take_profit', 'position_size', 'market_price'
        ]
        for field in decimal_fields:
            if field in data_copy and data_copy[field] is not None:
                if not isinstance(data_copy[field], Decimal):
                    data_copy[field] = Decimal(str(data_copy[field]))

        # Convert indicators dict
        if 'indicators' in data_copy:
            data_copy['indicators'] = {
                k: Decimal(str(v)) if not isinstance(v, Decimal) else v
                for k, v in data_copy['indicators'].items()
            }

        # Convert enum fields
        if 'signal_type' in data_copy and isinstance(data_copy['signal_type'], str):
            data_copy['signal_type'] = SignalType(data_copy['signal_type'])
        if 'strength' in data_copy and isinstance(data_copy['strength'], str):
            data_copy['strength'] = SignalStrength(data_copy['strength'])

        return cls(**data_copy)

    class Config:
        """Pydantic configuration."""
        json_encoders = {
            Decimal: str,
            datetime: lambda v: v.isoformat(),
        }


class SignalCollection(BaseModel):
    """Collection of signals for analysis.

    Aggregates multiple signals with utility methods for filtering and analysis.
    """

    signals: List[Signal] = Field(default_factory=list, description="List of signals")
    timestamp: datetime = Field(
        default_factory=datetime.utcnow,
        description="Collection timestamp"
    )

    def add_signal(self, signal: Signal) -> None:
        """Add a signal to the collection."""
        self.signals.append(signal)

    def filter_by_symbol(self, symbol: str) -> List[Signal]:
        """Filter signals by symbol."""
        symbol = symbol.upper()
        return [s for s in self.signals if s.symbol == symbol]

    def filter_by_type(self, signal_type: SignalType) -> List[Signal]:
        """Filter signals by type."""
        return [s for s in self.signals if s.signal_type == signal_type]

    def filter_by_strength(self, min_strength: SignalStrength) -> List[Signal]:
        """Filter signals by minimum strength."""
        strength_order = {
            SignalStrength.WEAK: 1,
            SignalStrength.MODERATE: 2,
            SignalStrength.STRONG: 3,
            SignalStrength.VERY_STRONG: 4,
        }
        min_level = strength_order[min_strength]
        return [
            s for s in self.signals
            if strength_order[s.strength] >= min_level
        ]

    def filter_by_confidence(self, min_confidence: Decimal) -> List[Signal]:
        """Filter signals by minimum confidence."""
        return [s for s in self.signals if s.confidence >= min_confidence]

    def filter_active(self) -> List[Signal]:
        """Filter active (non-expired) signals."""
        return [s for s in self.signals if not s.is_expired()]

    def get_buy_signals(self) -> List[Signal]:
        """Get all buy signals."""
        return [s for s in self.signals if s.is_buy()]

    def get_sell_signals(self) -> List[Signal]:
        """Get all sell signals."""
        return [s for s in self.signals if s.is_sell()]

    def get_strong_signals(self) -> List[Signal]:
        """Get all strong signals."""
        return [s for s in self.signals if s.is_strong()]

    def count(self) -> int:
        """Count total signals."""
        return len(self.signals)

    def average_confidence(self) -> Decimal:
        """Calculate average confidence of all signals."""
        if not self.signals:
            return Decimal('0')
        return sum(s.confidence for s in self.signals) / len(self.signals)

    def consensus_signal(self, symbol: str) -> Optional[SignalType]:
        """Determine consensus signal for a symbol.

        Returns the most common signal type for the symbol.
        """
        symbol_signals = self.filter_by_symbol(symbol)
        if not symbol_signals:
            return None

        # Count signal types weighted by confidence
        type_weights: Dict[SignalType, Decimal] = {}
        for signal in symbol_signals:
            signal_type = signal.signal_type
            if signal_type not in type_weights:
                type_weights[signal_type] = Decimal('0')
            type_weights[signal_type] += signal.confidence

        # Return type with highest weight
        if type_weights:
            return max(type_weights.items(), key=lambda x: x[1])[0]
        return None

    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary representation."""
        return {
            'signals': [s.to_dict() for s in self.signals],
            'timestamp': self.timestamp.isoformat(),
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> 'SignalCollection':
        """Create SignalCollection from dictionary."""
        data_copy = data.copy()

        # Convert timestamp
        if 'timestamp' in data_copy and isinstance(data_copy['timestamp'], str):
            data_copy['timestamp'] = datetime.fromisoformat(data_copy['timestamp'])

        # Convert signals
        if 'signals' in data_copy:
            data_copy['signals'] = [
                Signal.from_dict(s) if isinstance(s, dict) else s
                for s in data_copy['signals']
            ]

        return cls(**data_copy)

    class Config:
        """Pydantic configuration."""
        json_encoders = {
            Decimal: str,
            datetime: lambda v: v.isoformat(),
        }
